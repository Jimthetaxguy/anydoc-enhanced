/// A standard font's widths.
#[derive(Clone, Copy, Debug)]
pub(crate) enum Standard {
    /// Courier's, every glyph as wide.
    Fixed,
    Table(&'static [(char, u16)]),
}

impl Standard {
    /// The width in em of the glyph `character` reads as, where the font
    /// has one; a no-break space and a soft hyphen take the space's and the
    /// hyphen's.
    pub(crate) fn width(self, character: char) -> Option<f64> {
        let character = match character {
            '\u{00A0}' => ' ',
            '\u{00AD}' => '-',
            character => character,
        };
        match self {
            Standard::Fixed => Some(0.6),
            Standard::Table(table) => table
                .binary_search_by_key(&character, |&(glyph, _)| glyph)
                .ok()
                .map(|found| f64::from(table[found].1) / 1000.0),
        }
    }
}

/// The widths of the standard font `base_font` names, as pdf-inspector
/// tells one by its name: past a subset prefix, a name holding "courier",
/// "helvetica" or "arial", or "times", bold and italic or oblique where it
/// says so. `None` for any other, Symbol and ZapfDingbats among them.
pub(crate) fn widths(base_font: &[u8]) -> Option<Standard> {
    let name = String::from_utf8_lossy(base_font);
    let name = match name.split_once('+') {
        Some((prefix, rest))
            if prefix.len() == 6 && prefix.chars().all(|c| c.is_ascii_uppercase()) =>
        {
            rest
        }
        _ => &name,
    }
    .to_ascii_lowercase();
    let bold = name.contains("bold");
    let italic = name.contains("italic") || name.contains("oblique");
    if name.contains("courier") {
        Some(Standard::Fixed)
    } else if name.contains("helvetica") || name.contains("arial") {
        Some(Standard::Table(if bold {
            HELVETICA_BOLD
        } else {
            HELVETICA
        }))
    } else if name.contains("times") {
        Some(Standard::Table(match (bold, italic) {
            (false, false) => TIMES,
            (true, false) => TIMES_BOLD,
            (false, true) => TIMES_ITALIC,
            (true, true) => TIMES_BOLD_ITALIC,
        }))
    } else {
        None
    }
}

